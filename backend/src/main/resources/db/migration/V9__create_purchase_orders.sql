CREATE TABLE purchase_orders (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    po_number VARCHAR(40) NOT NULL,
    supplier_id BIGINT NOT NULL,
    status VARCHAR(20) NOT NULL,
    expected_delivery_date DATE NULL,
    reject_reason TEXT NULL,
    created_by BIGINT NOT NULL,
    created_at DATETIME(6) NOT NULL,
    approved_by BIGINT NULL,
    approved_at DATETIME(6) NULL,
    ordered_by BIGINT NULL,
    ordered_at DATETIME(6) NULL,
    received_by BIGINT NULL,
    received_at DATETIME(6) NULL,
    updated_at DATETIME(6) NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uk_purchase_orders_po_number UNIQUE (po_number),
    CONSTRAINT fk_purchase_orders_supplier FOREIGN KEY (supplier_id) REFERENCES suppliers(id),
    CONSTRAINT fk_purchase_orders_created_by FOREIGN KEY (created_by) REFERENCES users(id),
    CONSTRAINT fk_purchase_orders_approved_by FOREIGN KEY (approved_by) REFERENCES users(id),
    CONSTRAINT fk_purchase_orders_ordered_by FOREIGN KEY (ordered_by) REFERENCES users(id),
    CONSTRAINT fk_purchase_orders_received_by FOREIGN KEY (received_by) REFERENCES users(id),
    CONSTRAINT chk_purchase_orders_status CHECK (status IN ('DRAFT', 'APPROVED', 'ORDERED', 'RECEIVED', 'REJECTED')),
    INDEX idx_purchase_orders_supplier (supplier_id),
    INDEX idx_purchase_orders_status (status),
    INDEX idx_purchase_orders_status_expected_delivery_date (status, expected_delivery_date),
    INDEX idx_purchase_orders_created_at (created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE purchase_order_items (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    purchase_order_id BIGINT NOT NULL,
    material_id BIGINT NOT NULL,
    quantity DECIMAL(19,4) NOT NULL,
    unit_price DECIMAL(19,4) NOT NULL,
    unit VARCHAR(10) NOT NULL,
    recommendation_id BIGINT NULL,
    supplier_recommendation_result_id BIGINT NULL,
    recommended_supplier_id_snapshot BIGINT NULL,
    recommended_quantity_snapshot DECIMAL(19,4) NULL,
    supplier_override_reason TEXT NULL,
    quantity_override_reason TEXT NULL,
    created_at DATETIME(6) NOT NULL,
    CONSTRAINT fk_purchase_order_items_purchase_order FOREIGN KEY (purchase_order_id) REFERENCES purchase_orders(id),
    CONSTRAINT fk_purchase_order_items_material FOREIGN KEY (material_id) REFERENCES materials(id),
    CONSTRAINT uk_purchase_order_items_purchase_order_material UNIQUE (purchase_order_id, material_id),
    CONSTRAINT chk_purchase_order_items_quantity CHECK (quantity > 0),
    CONSTRAINT chk_purchase_order_items_unit_price CHECK (unit_price >= 0),
    INDEX idx_purchase_order_items_purchase_order (purchase_order_id),
    INDEX idx_purchase_order_items_material (material_id),
    INDEX idx_purchase_order_items_recommendation (recommendation_id),
    INDEX idx_purchase_order_items_supplier_recommendation_result (supplier_recommendation_result_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
